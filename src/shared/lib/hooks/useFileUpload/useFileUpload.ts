import { useState, useCallback, useRef } from 'react';

/**
 * Импортируем базовые хуки из библиотеки React:
 *
 * - useState: для управления состоянием загрузки, ошибок и результата
 * - useCallback: для мемоизации функций (предотвращения лишних ререндеров)
 * - useRef: для хранения ссылок на функции без вызова ререндеров
 *
 * Эти хуки позволяют создать эффективный и производительный кастомный хук.
 */

// ============================================
// 2. ИНТЕРФЕЙС КОНФИГУРАЦИИ
// ============================================

/**
 * Конфигурация загрузки файла
 *
 * Этот интерфейс определяет все параметры, которые можно передать в хук.
 * Он является гибким и позволяет настроить хук под любые сценарии загрузки файлов.
 */
interface FileUploadConfig<T = unknown> {
	/**
	 * Функция загрузки файла на сервер
	 *
	 * ОБЯЗАТЕЛЬНЫЙ параметр.
	 *
	 * Эта функция принимает объект типа File и возвращает промис с результатом.
	 * Обычно это асинхронная функция, которая отправляет файл на сервер через fetch или axios.
	 *
	 * Пример:
	 * @example
	 * uploadFn: async (file: File) => {
	 *   const formData = new FormData();
	 *   formData.append('file', file);
	 *
	 *   const response = await fetch('/api/upload', {
	 *     method: 'POST',
	 *     body: formData
	 *   });
	 *
	 *   return await response.json();
	 * }
	 *
	 * @param file - объект файла, выбранный пользователем
	 * @returns Promise с данными ответа от сервера (типизирован через дженерик T)
	 */
	uploadFn: (file: File) => Promise<T>;

	/**
	 * Опциональная функция валидации файла
	 *
	 * НЕОБЯЗАТЕЛЬНЫЙ параметр.
	 *
	 * Вызывается ДО загрузки файла на сервер.
	 * Позволяет проверить файл на соответствие требованиям:
	 * - тип файла (изображение, документ и т.д.)
	 * - размер файла
	 * - разрешения и т.д.
	 *
	 * Возвращает промис с объектом:
	 * - { valid: true } - файл прошел валидацию
	 * - { valid: false, error: 'Сообщение об ошибке' } - файл не прошел валидацию
	 *
	 * Пример:
	 * @example
	 * validateFn: async (file: File) => {
	 *   if (!file.type.startsWith('image/')) {
	 *     return { valid: false, error: 'Файл должен быть изображением' };
	 *   }
	 *
	 *   if (file.size > 5 * 1024 * 1024) {
	 *     return { valid: false, error: 'Файл слишком большой (максимум 5 МБ)' };
	 *   }
	 *
	 *   // Проверка через создание изображения
	 *   const img = new Image();
	 *   img.src = URL.createObjectURL(file);
	 *
	 *   return new Promise((resolve) => {
	 *     img.onload = () => resolve({ valid: true });
	 *     img.onerror = () => resolve({
	 *       valid: false,
	 *       error: 'Файл поврежден или не является валидным изображением'
	 *     });
	 *   });
	 * }
	 *
	 * @param file - объект файла для проверки
	 * @returns промис с результатом валидации
	 */
	validateFn?: (file: File) => Promise<{ valid: boolean; error?: string }>;

	/**
	 * Функция извлечения данных из ответа сервера
	 *
	 * НЕОБЯЗАТЕЛЬНЫЙ параметр.
	 *
	 * Сервер может возвращать разные структуры данных.
	 * Эта функция позволяет извлечь только нужную часть ответа.
	 *
	 * Например, сервер возвращает:
	 * @example
	 * {
	 *   file: "avatar_123.jpg",
	 *   file_url: "https://example.com/uploads/avatar_123.jpg",
	 *   uploaded_at: "2026-02-03T10:00:00Z"
	 * }
	 *
	 * А компоненту нужен только URL:
	 * @example
	 * extractData: (response) => response.file_url
	 *
	 * Или можно трансформировать данные:
	 * @example
	 * extractData: (response) => ({
	 *   url: response.file_url,
	 *   name: response.file,
	 *   timestamp: new Date(response.uploaded_at)
	 * })
	 *
	 * @param response - полный ответ от сервера (типизирован через дженерик T)
	 * @returns извлеченные или трансформированные данные
	 */
	// eslint-disable-next-line @typescript-eslint/no-explicit-any
	extractData?: (response: T) => any;

	/**
	 * Сообщения об ошибках (опционально)
	 *
	 * НЕОБЯЗАТЕЛЬНЫЙ параметр.
	 *
	 * Позволяет кастомизировать сообщения об ошибках на нужном языке.
	 * Если не указать - будут использоваться сообщения по умолчанию.
	 *
	 * @example
	 * errorMessages: {
	 *   validationFailed: 'Неверный формат файла',
	 *   uploadFailed: 'Не удалось загрузить файл',
	 *   extractFailed: 'Ошибка обработки ответа сервера'
	 * }
	 *
	 * @property validationFailed - ошибка валидации файла
	 * @property uploadFailed - ошибка загрузки на сервер
	 * @property extractFailed - ошибка извлечения данных из ответа
	 */
	errorMessages?: {
		validationFailed?: string;
		uploadFailed?: string;
		extractFailed?: string;
	};
}

// ============================================
// 3. ИНТЕРФЕЙС РЕЗУЛЬТАТА
// ============================================

/**
 * Результат хука загрузки файла
 *
 * Этот интерфейс определяет, что возвращает хук.
 * Компонент получает все необходимые методы и состояния для работы с загрузкой.
 */
interface UseFileUploadResult<T = unknown> {
	/**
	 * Функция загрузки файла
	 *
	 * Основной метод хука. Вызывается для загрузки файла.
	 *
	 * @example
	 * const handleFileChange = async (e: React.ChangeEvent<HTMLInputElement>) => {
	 *   const file = e.target.files?.[0];
	 *   if (!file) return;
	 *
	 *   try {
	 *     const result = await upload(file);
	 *     console.log('Файл загружен:', result);
	 *   } catch (error) {
	 *     console.error('Ошибка загрузки:', error);
	 *   }
	 * };
	 *
	 * @param file - объект файла для загрузки
	 * @returns промис с ответом от сервера (типизирован через дженерик T)
	 */
	upload: (file: File) => Promise<T>;

	/**
	 * Статус загрузки
	 *
	 * Булево значение, указывающее, идет ли сейчас загрузка файла.
	 *
	 * Используется для:
	 * - отображения индикатора загрузки (спиннера)
	 * - блокировки кнопки во время загрузки
	 * - отключения инпута во время загрузки
	 *
	 * @example
	 * {isUploading && <Spinner />}
	 * <Button disabled={isUploading}>
	 *   {isUploading ? 'Загрузка...' : 'Загрузить'}
	 * </Button>
	 */
	isUploading: boolean;

	/**
	 * Ошибка загрузки
	 *
	 * Строка с сообщением об ошибке или null, если ошибки нет.
	 *
	 * Хранится в состоянии компонента, поэтому при изменении вызывает ререндер.
	 *
	 * @example
	 * {error && <ErrorMessage message={error} />}
	 *
	 * @type string | null
	 */
	error: string | null;

	/**
	 * Очистка ошибки
	 *
	 * Функция для сброса состояния ошибки.
	 *
	 * Полезно вызывать:
	 * - когда пользователь пытается загрузить файл снова
	 * - когда пользователь закрывает сообщение об ошибке
	 * - при изменении файла (новый файл - новая попытка)
	 *
	 * @example
	 * const handleRetry = () => {
	 *   clearError();
	 *   // Попробовать загрузить снова...
	 * };
	 *
	 * @example
	 * <ErrorMessage message={error} onClose={clearError} />
	 */
	clearError: () => void;

	/**
	 * Последний успешный результат
	 *
	 * Хранит данные из последней успешной загрузки.
	 *
	 * Если указана функция `extractData`, здесь будет результат этой функции.
	 * Если `extractData` не указана, здесь будет полный ответ от сервера.
	 *
	 * @example
	 * // После успешной загрузки аватара
	 * {lastResult && <img src={lastResult} alt="Аватар" />}
	 *
	 * @type any | null
	 */
	// eslint-disable-next-line @typescript-eslint/no-explicit-any
	lastResult: any | null;
}

// ============================================
// 4. ОСНОВНАЯ ФУНКЦИЯ ХУКА
// ============================================

/**
 * Универсальный хук для загрузки файлов
 *
 * Этот хук инкапсулирует всю логику загрузки файлов:
 * - валидацию
 * - отправку на сервер
 * - обработку ошибок
 * - извлечение данных
 *
 * Он является переиспользуемым и может применяться для загрузки любых типов файлов:
 * - аватаров
 * - документов
 * - изображений
 * - видео и т.д.
 *
 * @typeParam T - тип данных, возвращаемых функцией загрузки (по умолчанию unknown)
 * @param config - объект конфигурации с параметрами загрузки
 * @returns объект с методами и состояниями для работы с загрузкой
 *
 * @example
 * // Загрузка аватара
 * const { upload, isUploading, error } = useFileUpload({
 *   uploadFn: uploadAvatar,
 *   validateFn: validateImageFile,
 *   extractData: (response) => response.file_url,
 *   errorMessages: {
 *     validationFailed: 'Неверный формат аватара',
 *     uploadFailed: 'Не удалось загрузить аватар'
 *   }
 * });
 *
 * @example
 * // Загрузка документа
 * const { upload, isUploading } = useFileUpload({
 *   uploadFn: uploadDocument,
 *   extractData: (response) => response.document_id
 * });
 */
export const useFileUpload = <T = unknown>(
	config: FileUploadConfig<T>
): UseFileUploadResult<T> => {
	// Деструктуризация конфигурации
	// Извлекаем все параметры из объекта конфигурации для удобства использования
	const { uploadFn, validateFn, extractData, errorMessages } = config;

	// ============================================
	// 5. ИНИЦИАЛИЗАЦИЯ СОСТОЯНИЙ
	// ============================================

	/**
	 * Состояние загрузки
	 *
	 * Используется для отслеживания процесса загрузки.
	 *
	 * - Начальное значение: false (не загружаем)
	 * - Перед загрузкой: устанавливается в true
	 * - После загрузки (успешной или нет): устанавливается в false в блоке finally
	 *
	 * Это гарантирует, что состояние всегда корректно, даже если произошла ошибка.
	 */
	const [isUploading, setUploading] = useState(false);

	/**
	 * Состояние ошибки
	 *
	 * Хранит сообщение об ошибке или null, если ошибки нет.
	 *
	 * - Начальное значение: null (нет ошибки)
	 * - При ошибке: устанавливается сообщение об ошибке
	 * - При очистке: устанавливается в null через функцию clearError
	 * - Перед новой загрузкой: автоматически очищается (в функции upload)
	 */
	const [error, setError] = useState<string | null>(null);

	/**
	 * Состояние последнего результата
	 *
	 * Хранит данные из последней успешной загрузки.
	 *
	 * - Начальное значение: null (нет результата)
	 * - После успешной загрузки: устанавливается результат (полный или извлеченный)
	 * - При новой загрузке: перезаписывается новым результатом
	 *
	 * Это состояние полезно для:
	 * - отображения превью загруженного файла
	 * - сохранения ссылки на файл
	 * - отслеживания истории загрузок
	 */
	const [lastResult, setLastResult] = useState<unknown | null>(null);

	// ============================================
	// 6. СОЗДАНИЕ И ОБНОВЛЕНИЕ РЕФОВ
	// ============================================

	/**
	 * Реф для функции загрузки
	 *
	 * Зачем нужен реф вместо прямого использования функции?
	 *
	 * Проблема: если передать функцию в зависимости хука useCallback,
	 * то при каждом изменении этой функции (например, при ререндере родителя)
	 * будет пересоздаваться функция upload, что может вызвать лишние ререндеры.
	 *
	 * Решение: сохраняем функцию в реф, который не вызывает ререндеров при изменении.
	 * Внутри функции upload используем реф вместо замыкания.
	 *
	 * @example
	 * uploadFnRef.current(file) // Вместо: uploadFn(file)
	 */
	const uploadFnRef = useRef(uploadFn);

	/**
	 * Реф для функции валидации
	 *
	 * Аналогично функции загрузки - сохраняем в реф для предотвращения лишних ререндеров.
	 * Если валидация не передана, реф будет содержать undefined.
	 */
	const validateFnRef = useRef(validateFn);

	/**
	 * Реф для функции извлечения данных
	 *
	 * Сохраняем в реф для предотвращения лишних ререндеров.
	 * Если извлечение не передано, реф будет содержать undefined.
	 */
	const extractDataRef = useRef(extractData);

	/**
	 * Обновление рефов при каждом рендере
	 *
	 * Важно: эти строки выполняются при КАЖДОМ рендере компонента.
	 * Это гарантирует, что рефы всегда содержат актуальные версии функций.
	 *
	 * Почему не используем эффект (useEffect)?
	 * - useEffect выполняется ПОСЛЕ рендера
	 * - Здесь нужно обновить рефы ДО использования в функции upload
	 * - Поэтому обновляем рефы прямо в теле компонента
	 */
	uploadFnRef.current = uploadFn;
	validateFnRef.current = validateFn;
	extractDataRef.current = extractData;

	// ============================================
	// 7. ФУНКЦИЯ UPLOAD
	// ============================================

	/**
	 * Функция загрузки файла
	 *
	 * Это основной метод хука, который вызывается для загрузки файла.
	 *
	 * Функция обернута в useCallback для предотвращения лишних ререндеров.
	 * Зависимости: только errorMessages (редко меняется)
	 *
	 * @param file - объект файла для загрузки
	 * @returns промис с ответом от сервера
	 */
	const upload = useCallback(
		async (file: File): Promise<T> => {
			// ============================================
			// 7.1. УСТАНОВКА СОСТОЯНИЯ ЗАГРУЗКИ
			// ============================================

			/**
			 * Устанавливаем флаг загрузки в true
			 *
			 * Это вызовет ререндер компонента, и он сможет показать индикатор загрузки.
			 *
			 * @example
			 * {isUploading && <Spinner />}
			 */
			setUploading(true);

			/**
			 * Очищаем предыдущую ошибку
			 *
			 * Перед новой загрузкой сбрасываем ошибку, чтобы старое сообщение
			 * не показывалось во время новой загрузки.
			 *
			 * @example
			 * // Было: "Ошибка загрузки"
			 * // Стало: null (пока идет загрузка)
			 */
			setError(null);

			// ============================================
			// 7.2. БЛОК ОБРАБОТКИ ОШИБОК
			// ============================================

			/**
			 * Оборачиваем всю логику в try-catch-finally
			 *
			 * - try: основная логика загрузки
			 * - catch: обработка ошибок
			 * - finally: гарантированное выполнение (сброс флага загрузки)
			 */
			try {
				// ============================================
				// 7.2.1. ВАЛИДАЦИЯ ФАЙЛА (ЕСЛИ УКАЗАНА)
				// ============================================

				/**
				 * Проверяем, указана ли функция валидации
				 *
				 * Если реф содержит функцию (не undefined), выполняем валидацию.
				 * Если валидация не указана - пропускаем этот шаг.
				 */
				if (validateFnRef.current) {
					/**
					 * Выполняем валидацию файла
					 *
					 * Вызываем функцию валидации и ждем результата.
					 * Функция возвращает промис с объектом { valid: boolean, error?: string }
					 */
					const validation = await validateFnRef.current(file);

					/**
					 * Проверяем результат валидации
					 *
					 * Если файл не прошел валидацию (valid: false),
					 * выбрасываем ошибку с сообщением.
					 */
					if (!validation.valid) {
						/**
						 * Формируем сообщение об ошибке
						 *
						 * Приоритет:
						 * 1. Ошибка из функции валидации (если указана)
						 * 2. Кастомное сообщение из конфигурации
						 * 3. Сообщение по умолчанию
						 */
						const errorMsg =
							errorMessages?.validationFailed || 'Ошибка валидации файла';

						/**
						 * Выбрасываем ошибку
						 *
						 * Это прервет выполнение и перейдет в блок catch.
						 * Сообщение об ошибке будет использовано для установки состояния.
						 */
						throw new Error(validation.error || errorMsg);
					}
				}

				// ============================================
				// 7.2.2. ЗАГРУЗКА ФАЙЛА НА СЕРВЕР
				// ============================================

				/**
				 * Вызываем функцию загрузки
				 *
				 * Передаем файл в функцию загрузки и ждем ответа от сервера.
				 * Функция возвращает промис с данными ответа.
				 *
				 * @example
				 * // uploadFn может быть функцией типа:
				 * // uploadAvatar(file) => Promise<{ file: string, file_url: string }>
				 */
				const response = await uploadFnRef.current(file);

				// ============================================
				// 7.2.3. ИЗВЛЕЧЕНИЕ ДАННЫХ (ЕСЛИ УКАЗАНО)
				// ============================================

				/**
				 * Инициализируем переменную для извлеченных данных
				 *
				 * По умолчанию используем полный ответ от сервера.
				 * Если указана функция извлечения - перезапишем это значение.
				 */
				let extractedData: unknown = response;

				/**
				 * Проверяем, указана ли функция извлечения данных
				 *
				 * Если реф содержит функцию (не undefined), выполняем извлечение.
				 * Если извлечение не указано - используем полный ответ.
				 */
				if (extractDataRef.current) {
					/**
					 * Выполняем извлечение данных
					 *
					 * Вызываем функцию извлечения и передаем ей полный ответ.
					 * Функция может вернуть часть данных или трансформировать их.
					 */
					extractedData = extractDataRef.current(response);

					/**
					 * Проверяем результат извлечения
					 *
					 * Если функция вернула undefined или null,
					 * это означает, что извлечение не удалось.
					 * Выбрасываем ошибку.
					 */
					if (extractedData === undefined || extractedData === null) {
						/**
						 * Формируем сообщение об ошибке
						 *
						 * Приоритет:
						 * 1. Кастомное сообщение из конфигурации
						 * 2. Сообщение по умолчанию
						 */
						const errorMsg =
							errorMessages?.extractFailed ||
							'Не удалось извлечь данные из ответа';

						/**
						 * Выбрасываем ошибку
						 *
						 * Это прервет выполнение и перейдет в блок catch.
						 */
						throw new Error(errorMsg);
					}
				}

				// ============================================
				// 7.2.4. СОХРАНЕНИЕ РЕЗУЛЬТАТА
				// ============================================

				/**
				 * Сохраняем извлеченные данные в состояние
				 *
				 * Это вызовет ререндер компонента, и он сможет использовать
				 * данные из последней успешной загрузки.
				 *
				 * @example
				 * // После загрузки аватара:
				 * // {lastResult && <img src={lastResult} alt="Аватар" />}
				 */
				setLastResult(extractedData);

				/**
				 * Возвращаем полный ответ от сервера
				 *
				 * Важно: возвращаем именно полный ответ (response), а не извлеченные данные.
				 * Это позволяет компоненту получить доступ ко всем данным, если нужно.
				 *
				 * @example
				 * const result = await upload(file);
				 * // result = { file: '...', file_url: '...', ... }
				 */
				return response;

				// ============================================
				// 7.3. ОБРАБОТКА ОШИБОК
				// ============================================

				/**
				 * Блок обработки ошибок
				 *
				 * Срабатывает, если в блоке try произошла ошибка:
				 * - ошибка валидации
				 * - ошибка загрузки на сервер
				 * - ошибка извлечения данных
				 * - любая другая ошибка
				 *
				 * @param err - объект ошибки
				 */
			} catch (err) {
				/**
				 * Формируем сообщение об ошибке
				 *
				 * Проверяем тип ошибки:
				 * - Если это экземпляр класса Error - используем его сообщение
				 * - Иначе используем кастомное сообщение или сообщение по умолчанию
				 */
				const message =
					err instanceof Error
						? err.message
						: errorMessages?.uploadFailed || 'Ошибка загрузки файла';

				/**
				 * Устанавливаем сообщение об ошибке в состояние
				 *
				 * Это вызовет ререндер компонента, и он сможет показать ошибку.
				 *
				 * @example
				 * {error && <ErrorMessage message={error} />}
				 */
				setError(message);

				/**
				 * Логируем ошибку в консоль
				 *
				 * Для отладки и мониторинга ошибок.
				 * Используем консоль с эмодзи для лучшей видимости.
				 */
				console.error('❌ Ошибка загрузки файла:', err);

				/**
				 * Пробрасываем ошибку дальше
				 *
				 * Важно: не перехватываем ошибку полностью!
				 * Компонент, вызывающий функцию upload, должен иметь возможность
				 * обработать ошибку через try-catch.
				 *
				 * @example
				 * try {
				 *   await upload(file);
				 * } catch (error) {
				 *   // Обработка ошибки в компоненте
				 * }
				 */
				throw err;

				// ============================================
				// 7.4. ГАРАНТИРОВАННОЕ ВЫПОЛНЕНИЕ
				// ============================================

				/**
				 * Блок гарантированного выполнения
				 *
				 * Срабатывает ВСЕГДА, независимо от того, была ли ошибка или нет.
				 *
				 * Используется для сброса флага загрузки.
				 * Это гарантирует, что состояние всегда корректно.
				 */
			} finally {
				/**
				 * Устанавливаем флаг загрузки в false
				 *
				 * Это вызовет ререндер компонента, и он сможет скрыть индикатор загрузки.
				 *
				 * @example
				 * // Было: {isUploading && <Spinner />}
				 * // Стало: спиннер скрыт
				 */
				setUploading(false);
			}
		},
		/**
		 * Зависимости хука useCallback
		 *
		 * Функция upload будет пересоздаваться только при изменении этих зависимостей.
		 *
		 * Почему только errorMessages?
		 * - Функции (uploadFn, validateFn, extractData) сохранены в рефах
		 * - Рефы не вызывают ререндеров при изменении
		 * - Поэтому функция upload не зависит от этих функций напрямую
		 * - errorMessages редко меняется, поэтому ререндеры будут минимальными
		 */
		[errorMessages]
	);

	// ============================================
	// 8. ФУНКЦИЯ CLEARERROR
	// ============================================

	/**
	 * Функция очистки ошибки
	 *
	 * Обернута в useCallback для предотвращения лишних ререндеров.
	 * Не имеет зависимостей (пустой массив).
	 *
	 * @example
	 * <Button onClick={clearError}>Закрыть ошибку</Button>
	 */
	const clearError = useCallback(() => {
		/**
		 * Устанавливаем состояние ошибки в null
		 *
		 * Это вызовет ререндер компонента, и сообщение об ошибке будет скрыто.
		 *
		 * @example
		 * // Было: {error && <ErrorMessage message={error} />}
		 * // Стало: сообщение скрыто
		 */
		setError(null);
	}, []);

	// ============================================
	// 9. ВОЗВРАТ РЕЗУЛЬТАТА
	// ============================================

	/**
	 * Возвращаем объект с методами и состояниями
	 *
	 * Этот объект будет доступен в компоненте, использующем хук.
	 *
	 * @example
	 * const { upload, isUploading, error, clearError, lastResult } = useFileUpload(...);
	 */
	return {
		/**
		 * Функция загрузки файла
		 *
		 * Основной метод для загрузки файлов.
		 */
		upload,

		/**
		 * Статус загрузки
		 *
		 * Используется для отображения индикатора загрузки.
		 */
		isUploading,

		/**
		 * Ошибка загрузки
		 *
		 * Используется для отображения сообщения об ошибке.
		 */
		error,

		/**
		 * Функция очистки ошибки
		 *
		 * Используется для скрытия сообщения об ошибке.
		 */
		clearError,

		/**
		 * Последний успешный результат
		 *
		 * Используется для отображения превью или сохранения данных.
		 */
		lastResult
	};
};
